// Unicode has dedicated subscript/superscript code points for digits and a
// limited set of symbols/letters — this is a pure character substitution,
// so unlike OCR it IS 100% reliable for anything in these tables. Anything
// outside the table (most letters) has no Unicode subscript/superscript
// form and is left unchanged, with a warning surfaced to the caller.

const SUB_MAP = {
  '0': '₀', '1': '₁', '2': '₂', '3': '₃', '4': '₄', '5': '₅', '6': '₆', '7': '₇', '8': '₈', '9': '₉',
  '+': '₊', '-': '₋', '=': '₌', '(': '₍', ')': '₎',
  a: 'ₐ', e: 'ₑ', h: 'ₕ', i: 'ᵢ', j: 'ⱼ', k: 'ₖ', l: 'ₗ', m: 'ₘ', n: 'ₙ', o: 'ₒ', p: 'ₚ',
  r: 'ᵣ', s: 'ₛ', t: 'ₜ', u: 'ᵤ', v: 'ᵥ', x: 'ₓ',
};

const SUPER_MAP = {
  '0': '⁰', '1': '¹', '2': '²', '3': '³', '4': '⁴', '5': '⁵', '6': '⁶', '7': '⁷', '8': '⁸', '9': '⁹',
  '+': '⁺', '-': '⁻', '=': '⁼', '(': '⁽', ')': '⁾',
  a: 'ᵃ', b: 'ᵇ', c: 'ᶜ', d: 'ᵈ', e: 'ᵉ', f: 'ᶠ', g: 'ᵍ', h: 'ʰ', i: 'ⁱ', j: 'ʲ', k: 'ᵏ',
  l: 'ˡ', m: 'ᵐ', n: 'ⁿ', o: 'ᵒ', p: 'ᵖ', r: 'ʳ', s: 'ˢ', t: 'ᵗ', u: 'ᵘ', v: 'ᵛ', w: 'ʷ', x: 'ˣ', y: 'ʸ', z: 'ᶻ',
};

function convert(text, map) {
  let unmapped = 0;
  const result = [...text].map((ch) => {
    const lower = ch.toLowerCase();
    if (map[lower]) return map[lower];
    unmapped++;
    return ch;
  }).join('');
  return { result, unmapped };
}

export function toSubscript(text) {
  return convert(text, SUB_MAP);
}

export function toSuperscript(text) {
  return convert(text, SUPER_MAP);
}
